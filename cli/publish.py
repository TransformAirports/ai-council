def _add_page_numbers(doc: Document) -> None:
    """Add understated Council identity and a PAGE field."""
    section = doc.sections[0]
    header = section.header
    header.is_linked_to_previous = False
    header_para = header.paragraphs[0] if header.paragraphs else header.add_paragraph()
    header_para.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    for run in list(header_para.runs):
        run.text = ""
    header_run = header_para.add_run("TRANSFORM AIRPORTS  /  AI RESEARCH COUNCIL")
    header_run.font.size = Pt(7.5)
    header_run.font.name = BODY_FONT
    header_run.font.bold = True
    header_run.font.color.rgb = INK_SOFT

    footer = section.footer
    footer.is_linked_to_previous = False
    para = footer.paragraphs[0] if footer.paragraphs else footer.add_paragraph()
    para.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    for r in list(para.runs):
        r.text = ""

    run = para.add_run("FINAL  •  ")
    run.font.size = Pt(7.5)
    run.font.name = BODY_FONT
    run.font.color.rgb = INK_SOFT

    # { PAGE } field
    fld_begin = OxmlElement("w:fldChar")
    fld_begin.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = "PAGE"
    fld_sep = OxmlElement("w:fldChar")
    fld_sep.set(qn("w:fldCharType"), "separate")
    fld_end = OxmlElement("w:fldChar")
    fld_end.set(qn("w:fldCharType"), "end")
    num_run = para.add_run()
    num_run.font.size = Pt(7.5)
    num_run.font.name = BODY_FONT
    num_run.font.color.rgb = INK_SOFT
    num_run._r.append(fld_begin)
    num_run._r.append(instr)
    num_run._r.append(fld_sep)
    num_run._r.append(fld_end)


