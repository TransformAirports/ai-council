def _styled_run(paragraph, text: str, *, bold: bool = False, italic: bool = False,
                size: int = 11, color: RGBColor | None = None):
    run = paragraph.add_run(text)
    run.bold = bold
    run.italic = italic
    run.font.size = Pt(size)
    run.font.name = BODY_FONT
    if color is not None:
        run.font.color.rgb = color
    return run


def _add_methodology_page(doc: Document, agents_used: list[str]) -> None:
    """A one-page reader-facing method and source-discipline appendix.

    Internal filenames, agent identities, and stage labels do not belong in a
    distribution report. The reader gets the information that matters:
    independence, adversarial challenge, verification, human accountability,
    and the number of specialist perspectives commissioned.
    """
    body_sz = 10
    gap = Pt(5)

    def para(space_after=gap):
        p = doc.add_paragraph()
        p.paragraph_format.space_after = space_after
        p.paragraph_format.line_spacing = 1.12
        return p

    def subhead(text: str) -> None:
        p = para(space_after=Pt(3))
        p.paragraph_format.space_before = Pt(7)
        r = _styled_run(p, text.upper(), bold=True, size=9, color=BRAND_NAVY)
        # letter-spacing effect via the spacing property isn't exposed; caps
        # plus color reads as a label without one.

    h = doc.add_heading(level=1)
    h.paragraph_format.space_after = Pt(6)
    r = h.add_run("Method and source discipline")
    r.font.name = HEADING_FONT
    r.font.size = Pt(16)
    r.font.color.rgb = BRAND_NAVY

    intro = para()
    _styled_run(
        intro,
        "This report is the product of the Transform Airports AI Research "
        "Council. The process combines independent specialist research, "
        "adversarial challenge, editorial refinement, source verification, and "
        "human review. It is designed to reduce single-model blind spots while "
        "keeping human decision-makers accountable for the conclusions.",
        size=body_sz,
    )

    stages = [
        ("Independent lines of inquiry.",
         f"{len(agents_used) or 'Multiple'} specialist perspective"
         f"{'s were' if len(agents_used) != 1 else ' was'} commissioned without "
         "cross-reading, limiting premature consensus."),
        ("Adversarial synthesis.",
         "The combined argument was challenged for weak evidence, omitted "
         "counterexamples, causal overreach, and impractical recommendations, "
         "then revised."),
        ("Editorial and source review.",
         "The revised argument was edited for clarity and checked claim by "
         "claim against the cited research record. Unsupported claims were "
         "removed or marked for human review."),
        ("Human accountability.",
         "Human review remains required before any operational, financial, "
         "legal, procurement, safety, or policy decision."),
    ]
    for i, (label, body) in enumerate(stages, 1):
        p = para(space_after=Pt(3))
        _styled_run(p, f"{i}.  {label} ", bold=True, size=body_sz)
        _styled_run(p, body, size=body_sz)

    subhead("Source standard")
    p = para()
    _styled_run(
        p,
        "Material numbers and attributed claims should resolve to numbered "
        "notes. Primary airport, government, regulatory, audited financial, "
        "contractual, or peer-reviewed sources take precedence. Every chart "
        "should state its unit, denominator, time period, and source.",
        size=body_sz,
        color=INK_SOFT,
    )

    note = para(space_after=Pt(0))
    note.paragraph_format.space_before = Pt(7)
    _styled_run(
        note,
        "Technical documentation for the analytical method is available at: ",
        size=8.5, color=INK_SOFT,
    )
    _styled_run(note, AGENTS_DOC_URL, size=8.5, color=BRAND_NAVY)

    doc.add_page_break()


def _add_compact_title_block(
    doc: Document,
    title: str,
    run_date: str,
    logo: Path | None,
    format_label: str,
    revision_label: str | None = None,
) -> None:
    """Page-one header for short formats (brief, recommendations) — no cover page."""
    if logo is not None:
        logo_para = doc.add_paragraph()
        logo_para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = logo_para.add_run()
        run.add_picture(str(logo), width=Inches(3.0))

    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.space_before = Pt(8)
    run = p.add_run(title)
    run.bold = True
    run.font.size = Pt(22)
    run.font.name = HEADING_FONT
    run.font.color.rgb = BRAND_NAVY

    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    parts = [format_label, ATTRIBUTION, run_date]
    if revision_label:
        parts.insert(1, revision_label)
    run = p.add_run("  ·  ".join(parts))
    run.font.size = Pt(10)
    run.font.name = BODY_FONT
    run.font.color.rgb = INK_SOFT

