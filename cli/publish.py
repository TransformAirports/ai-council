def discover_reports(runs_dir: Path = RUNS_DIR) -> list[ReportSource]:
    # One logical report may have multiple dated archives. Keep only the
    # newest exact slug match; callers should never receive an arbitrary
    # historical duplicate.
    latest: dict[str, ReportSource] = {}
    if not runs_dir.is_dir():
        return []
    for archive_dir in sorted(p for p in runs_dir.iterdir() if p.is_dir()):
        m = ARCHIVE_DIR_PATTERN.match(archive_dir.name)
        if not m:
            continue
        slug = m.group(1)
        stage4 = archive_dir / "stage4"
        if not stage4.is_dir():
            continue
        stage4_docx = stage4 / f"{slug}.docx"
        if not stage4_docx.is_file():
            continue
        final_md = archive_dir / "stage3" / "final-draft.md"
        archived_prompt = archive_dir / "run-prompt.md"
        live_prompt = RUN_PROMPTS_DIR / f"{slug}.md"
        run_file = (
            archived_prompt
            if archived_prompt.is_file()
            else live_prompt if live_prompt.is_file() else None
        )
        latest[slug] = ReportSource(
            slug=slug,
            archive_dir=archive_dir,
            stage4_docx=stage4_docx,
            final_md=final_md if final_md.is_file() else None,
            run_file=run_file,
        )
    return sorted(latest.values(), key=lambda item: item.slug)


